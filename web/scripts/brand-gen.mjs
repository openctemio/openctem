#!/usr/bin/env node
/**
 * Brand generator: the one place the OpenCTEM logo is turned into code.
 *
 * Source of truth: the SVG files in src/assets/brand/ (master drawings of the
 * Scope "Caught" symbol and the outlined Sora wordmark). This script derives
 * everything else from them, so no logo geometry is copied by hand:
 *
 *   src/assets/logo.tsx                 the shared React components
 *   src/assets/brand-data.generated.ts  the icon/OG drawings as strings (icon routes)
 *   src/assets/brand/manifest.json      sha256 of every source SVG
 *   public/brand/*.png                  manifest icons (192, 512, maskable 512)
 *   ../api/pkg/email/assets/logo@2x.png e-mail header (embedded, never remote)
 *
 * Usage:
 *   node scripts/brand-gen.mjs          write everything
 *   node scripts/brand-gen.mjs --check  fail if a text output is stale (CI)
 */
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const brandDir = join(root, 'src/assets/brand')
const check = process.argv.includes('--check')

const read = (name) => readFileSync(join(brandDir, name), 'utf8').trim()

/** viewBox and inner markup of a brand SVG (the <title> is dropped). */
function parts(name) {
  const svg = read(name)
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1]
  const inner = /<title>[^<]*<\/title>([\s\S]*)<\/svg>$/.exec(svg)?.[1]
  if (!viewBox || inner === undefined) throw new Error(`${name}: not a brand SVG`)
  return { viewBox, inner }
}

const camel = (attr) => attr.replace(/-([a-z])/g, (_, c) => c.toUpperCase())

/** Brand SVG markup as JSX; the marker square takes `markerColor`. */
function jsx(inner) {
  return inner
    .replace(/<rect ([^>]*?)fill="currentColor"/g, '<rect $1fill={markerColor}')
    .replace(/ ([a-z]+(?:-[a-z]+)+)=/g, (_, a) => ` ${camel(a)}=`)
}

const symbol = {
  master: parts('symbol.svg'),
  s32: parts('symbol-32.svg'),
  s16: parts('symbol-16.svg'),
}
const wordmark = parts('wordmark.svg')
const lockup = parts('lockup.svg')
const stacked = parts('lockup-stacked.svg')

function component(name, doc, p, testId, defaults) {
  return `/** ${doc} */
export function ${name}({ className, ${jsx(p.inner).includes('markerColor') ? 'markerColor = MARKER' : 'markerColor: _markerColor'}, ...props }: LogoProps) {
  return (
    <svg
      viewBox="${p.viewBox}"
      xmlns="http://www.w3.org/2000/svg"
      className={cn('${defaults}', className)}
      role="img"
      aria-label="OpenCTEM"
      data-testid="${testId}"
      {...props}
    >
      ${jsx(p.inner)}
    </svg>
  )
}
`
}

const symbolCut = (key, cut) => `    <svg
      viewBox="${symbol[key].viewBox}"
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      className={cn('size-6', className)}
      role="img"
      aria-label="OpenCTEM"
      data-testid="logo-symbol"
      data-cut="${cut}"
      {...props}
    >
      ${jsx(symbol[key].inner)}
    </svg>`

const logoTsx = `// GENERATED by web/scripts/brand-gen.mjs from src/assets/brand/*.svg.
// Do not edit by hand: change the SVG masters and run \`node scripts/brand-gen.mjs\`.
import { type SVGProps } from 'react'
import { cn } from '@/lib/utils'

/**
 * OpenCTEM logo: the Scope "Caught" symbol (two corner brackets with the
 * marker caught in the open corner) and the outlined Sora wordmark.
 * Construction, colour, clear space and minimum sizes are in
 * \`api/docs/architecture/brand.md\` and \`src/assets/brand/README.md\`.
 *
 * Every part is a path or a shape (nothing depends on installed fonts) and
 * draws in \`currentColor\`. The marker square is the only accent: it takes
 * \`--brand\` (teal, brighter on dark) unless \`markerColor\` is given.
 */
interface LogoProps extends SVGProps<SVGSVGElement> {
  /** Accent colour of the marker square. Defaults to the \`--brand\` token. */
  markerColor?: string
}

const MARKER = 'var(--brand)'

/** Symbol drawn at \`size\` px or smaller uses the 16 px cut, up to 40 px the 32 px cut. */
export const LOGO_CUT_MAX_16 = 24
export const LOGO_CUT_MAX_32 = 40

interface LogoSymbolProps extends LogoProps {
  /** Rendered size in px; picks the drawing (16 px cut, 32 px cut, master). */
  size?: number
}

/**
 * The symbol on its own (collapsed sidebar, rails, inline). The drawing is
 * chosen by \`size\`: at 24 px or less the 16 px cut, up to 40 px the 32 px
 * cut, above that the master, so every edge lands on whole pixels.
 */
export function Logo({ className, markerColor = MARKER, size = 24, ...props }: LogoSymbolProps) {
  if (size <= LOGO_CUT_MAX_16) {
    return (
${symbolCut('s16', '16')}
    )
  }
  if (size <= LOGO_CUT_MAX_32) {
    return (
${symbolCut('s32', '32')}
    )
  }
  return (
${symbolCut('master', 'master')}
  )
}

${component('LogoWordmark', 'The outlined "OpenCTEM" wordmark alone.', wordmark, 'logo-wordmark', 'h-5 w-auto')}
${component('LogoFull', 'Horizontal lockup (symbol + wordmark, 6.5:1): sign-in, legal pages, expanded sidebar.', lockup, 'logo-full', 'h-5 w-auto')}
${component('LogoStacked', 'Stacked lockup (symbol over the wordmark, 1.8:1).', stacked, 'logo-stacked', 'h-16 w-auto')}`

/** Strings the icon routes draw (satori renders an SVG data URI). */
const dataTs = `// GENERATED by web/scripts/brand-gen.mjs from src/assets/brand/*.svg. Do not edit.
export const FAVICON_16_SVG = ${JSON.stringify(read('favicon-16.svg'))}
export const FAVICON_32_SVG = ${JSON.stringify(read('favicon-32.svg'))}
export const APP_ICON_SVG = ${JSON.stringify(read('app-icon.svg'))}
export const MASKABLE_SVG = ${JSON.stringify(read('maskable-512.svg'))}
export const OG_IMAGE_SVG = ${JSON.stringify(read('og-image.svg'))}
`

const sha = (s) => createHash('sha256').update(s).digest('hex')
const files = {}
for (const f of readdirSync(brandDir)
  .filter((n) => n.endsWith('.svg'))
  .sort()) {
  files[f] = sha(readFileSync(join(brandDir, f)))
}
const manifest =
  JSON.stringify({ source: 'research/309-logo (Scope "Caught" + Sora 600)', files }, null, 2) + '\n'

const outputs = [
  [join(root, 'src/assets/logo.tsx'), logoTsx],
  [join(root, 'src/assets/brand-data.generated.ts'), dataTs],
  [join(brandDir, 'manifest.json'), manifest],
]

// Outputs are formatted with the repo's prettier config, so the generated
// files pass the same format check as hand-written ones.
const prettier = await import('prettier')
const formatted = []
for (const [path, content] of outputs) {
  const config = (await prettier.resolveConfig(path)) ?? {}
  formatted.push([path, await prettier.format(content, { ...config, filepath: path })])
}

let stale = 0
for (const [path, content] of formatted) {
  let current = null
  try {
    current = readFileSync(path, 'utf8')
  } catch {
    // missing file counts as stale
  }
  if (current === content) continue
  if (check) {
    console.error(`stale: ${path}`)
    stale++
  } else {
    writeFileSync(path, content)
  }
}
if (check) {
  if (stale) {
    console.error('Run: node scripts/brand-gen.mjs')
    process.exit(1)
  }
  process.exit(0)
}

// Raster outputs (not checked: PNG bytes depend on the encoder version).
const { default: sharp } = await import('sharp')
const png = async (svgName, size, outPath) => {
  mkdirSync(dirname(outPath), { recursive: true })
  await sharp(readFileSync(join(brandDir, svgName)), { density: 384 })
    .resize(size.w, size.h)
    .png({ compressionLevel: 9 })
    .toFile(outPath)
}
await png('app-icon.svg', { w: 192, h: 192 }, join(root, 'public/brand/icon-192.png'))
await png('app-icon.svg', { w: 512, h: 512 }, join(root, 'public/brand/icon-512.png'))
await png('maskable-512.svg', { w: 512, h: 512 }, join(root, 'public/brand/maskable-512.png'))

// E-mail header: the ink lockup at 2x of its 140 x 22 px display size.
const ink = read('lockup.svg')
  .replace(/currentColor/g, '#0A1628')
  .replace(/(<rect [^>]*fill=")#0A1628/, '$1#0D9488')
mkdirSync(join(root, '../api/pkg/email/assets'), { recursive: true })
await sharp(Buffer.from(ink), { density: 384 })
  .resize(280, 43)
  .png({ compressionLevel: 9 })
  .toFile(join(root, '../api/pkg/email/assets/logo@2x.png'))
console.log('brand assets written')

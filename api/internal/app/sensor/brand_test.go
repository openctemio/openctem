package sensor

import (
	"strings"
	"testing"

	"github.com/openctemio/openctem/api/pkg/brand"
	sensordom "github.com/openctemio/openctem/api/pkg/domain/sensor"
)

// Generated sensor configuration and check explanations name the instance
// brand and link its documentation; technical identifiers stay.
func TestBrandInSensorOutputs(t *testing.T) {
	e := configCheckCatalog[0]
	id := strings.ReplaceAll(e.ID, "*", "semgrep")
	check := sensordom.ConfigCheck{ID: id, Code: e.Code, Params: fullParams()}
	if got := ExplainCheck(check).DocsURL; !strings.HasPrefix(got, "https://docs.openctem.io/") {
		t.Fatalf("default docs link changed: %q", got)
	}
	def := render(t, templateSources[0], fullData(t)).Docker
	if !strings.Contains(def, "Generated by OpenCTEM at") {
		t.Fatal("default generated header changed")
	}

	b := brand.Default()
	b.Name, b.DocsURL = "Example Exposure", "https://docs.example.com"
	brand.SetInstance(b)
	t.Cleanup(func() { brand.SetInstance(brand.Default()) })

	if got := ExplainCheck(check).DocsURL; !strings.HasPrefix(got, "https://docs.example.com/sensors/troubleshooting/#") {
		t.Errorf("docs link not on the brand's site: %q", got)
	}
	for _, dir := range templateSources {
		out := render(t, dir, fullData(t))
		for format, text := range map[string]string{"docker": out.Docker, "compose": out.Compose} {
			if strings.Contains(text, "OpenCTEM") {
				t.Errorf("%s %s still names OpenCTEM", dir, format)
			}
			if !strings.Contains(text, "Generated by Example Exposure at") {
				t.Errorf("%s %s does not name the brand", dir, format)
			}
			if !strings.Contains(text, "ghcr.io/openctemio/") {
				t.Errorf("%s %s lost the technical image name", dir, format)
			}
		}
	}
}

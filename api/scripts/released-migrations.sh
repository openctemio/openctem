#!/usr/bin/env bash
# released-migrations.sh [--check]
#
# Writes api/migrations/released.json: for every release tag (v*) that still
# shipped the earlier migration tool (golang-migrate; no api/cmd/openctem-migrate
# in the tag), exactly which migration versions the tag contained. Tags with
# the same set are grouped.
#
# openctem-migrate needs it to take over a database the earlier tool
# migrated (docs/rfcs/RFC-130-migration-applied-set.md): that tool keeps only
# its highest version V, and a migration merged with a number below V after
# the release was cut (003420 after v0.15.4 shipped 003428) was never applied
# there. The runner records as applied only the files of the release whose
# highest version is V; every other file stays pending and runs.
#
# --check: fail when the committed file differs from what the tags give
# (CI; needs the tags, e.g. actions/checkout with fetch-depth: 0).
# Run from anywhere inside the repository.
#
# Tests: api/scripts/released-migrations.test.sh
set -euo pipefail

root="$(git rev-parse --show-toplevel)"
out="$root/api/migrations/released.json"

generate() {
  local t
  git -C "$root" tag -l 'v*' | sort -V | while IFS= read -r t; do
    git -C "$root" cat-file -e "$t:api/migrations" 2>/dev/null || continue
    if git -C "$root" cat-file -e "$t:api/cmd/openctem-migrate" 2>/dev/null; then continue; fi
    vs="$(git -C "$root" ls-tree --name-only "$t" api/migrations/ \
      | sed -n 's#^api/migrations/\([0-9]\{1,13\}\)_.*\.up\.sql$#\1#p' \
      | sed 's/^0*//' | sort -n | paste -sd, -)"
    [[ -n "$vs" ]] && echo "$t $vs"
  done | awk '
    {
      if (!($2 in idx)) { idx[$2] = ++n; set[n] = $2; tags[n] = "\"" $1 "\"" }
      else { tags[idx[$2]] = tags[idx[$2]] ", \"" $1 "\"" }
    }
    END {
      print "{"
      print "  \"about\": \"Migration versions each release tag shipped while it used the earlier migration tool. Generated by api/scripts/released-migrations.sh from the git tags; do not edit.\","
      print "  \"releases\": ["
      for (i = 1; i <= n; i++) printf "    {\"tags\": [%s], \"versions\": [%s]}%s\n", tags[i], set[i], (i < n ? "," : "")
      print "  ]"
      print "}"
    }'
}

if [[ "${1:-}" == --check ]]; then
  if [[ -z "$(git -C "$root" tag -l 'v*')" ]]; then
    echo "::error::released-migrations: no release tags in this clone (fetch them: git fetch --tags, or fetch-depth: 0)"
    exit 1
  fi
  if ! diff -u "$out" <(generate) >/dev/null 2>&1; then
    echo "::error::api/migrations/released.json does not match the release tags: regenerate it with make -C api migrations-released, then commit"
    diff -u "$out" <(generate) | head -20 || true
    exit 1
  fi
  echo "released.json matches the release tags"
  exit 0
fi
generate >"$out"
echo "wrote ${out#"$root"/}"

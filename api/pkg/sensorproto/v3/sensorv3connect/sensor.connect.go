// Sensor protocol v3: the sensor <-> platform transport
// (docs/rfcs/RFC-059-sensor-transport-v3.md).
//
// One service, two bindings served by the same handlers:
//   - gRPC over HTTP/2 on the dedicated sensor host, authenticated by a client
//     certificate from the sensor CA (mTLS, TLS 1.3);
//   - Connect over HTTPS (HTTP/1.1 or HTTP/2) under /api/v3/sensor on the
//     platform host, authenticated by an RFC 9421 request signature with the
//     sensor's key, as protocol v2.
//
// v3 carries the resource model of protocol v2 (RFC-026 results, RFC-029
// control plane). The envelope is typed: identifiers, sequence numbers, lease
// epochs, encodings, digests, entity tags and transport facts. A document whose
// schema is owned by another specification travels as its JSON bytes, unchanged:
// the heartbeat body and answer (RFC-029), commands (RFC-029), CTIS reports
// (RFC-026), the manifest (RFC-033), the config report and suppressions.
//
// Rules every message follows:
//   - No message names a tenant. The tenant and the sensor are those of the
//     authenticated identity (certificate or signature), never of a field.
//   - A command or report id of another sensor or tenant is NOT_FOUND.
//   - An error carries an openctem.sensor.v3.Problem detail: the RFC 9457
//     problem document v2 would have answered, with its HTTP status.


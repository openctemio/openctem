package report

import (
	"strings"
	"testing"
	"time"

	"github.com/openctemio/openctem/api/pkg/brand"
)

// The summary names the instance brand; the default stays OpenCTEM.
func TestGenerateSummaryHTML_NamesTheBrand(t *testing.T) {
	in := SummaryInput{TenantName: "Acme", GeneratedAt: time.Date(2026, 6, 8, 9, 0, 0, 0, time.UTC)}
	html, err := GenerateSummaryHTML(in)
	if err != nil || !strings.Contains(html, "Generated by OpenCTEM") {
		t.Fatalf("default brand: err=%v, footer missing", err)
	}

	b := brand.Default()
	b.Name = "Example & Co Exposure"
	brand.SetInstance(b)
	t.Cleanup(func() { brand.SetInstance(brand.Default()) })
	html, err = GenerateSummaryHTML(in)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(html, "Generated by Example &amp; Co Exposure") || strings.Contains(html, "OpenCTEM") {
		t.Errorf("summary does not name the configured brand (escaped)")
	}
}

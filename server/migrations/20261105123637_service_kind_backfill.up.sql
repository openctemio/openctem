    ('java-rmi', 'other'),
    ('jdwp', 'other'),
    ('ajp', 'other'),
    ('socks', 'other'),
    ('msrpc', 'other'),
    ('ipp', 'other'),
    ('jetdirect', 'other'),
    ('svn', 'other'),
    ('git', 'other'),
    ('coap', 'other'),
    ('echo', 'other'))
,
src AS (
    SELECT a.id, a.sub_type, a.discovery_tool,
           CASE WHEN length(a.properties->>'protocol') <= 64 THEN
               regexp_replace(regexp_replace(
                   rtrim(replace(replace(lower(btrim(a.properties->>'protocol')), '_', '-'), ' ', '-'), '?'),
                   '^ssl/', ''), '^tls/', '')
           END AS name,
           coalesce(length(a.properties->>'protocol') <= 64 AND btrim(a.properties->>'protocol') LIKE '%?', false) AS guess,
           CASE WHEN a.properties->>'port' ~ '^[0-9]{1,5}$' THEN (a.properties->>'port')::int END AS port,
           coalesce(nullif(lower(btrim(a.properties->>'transport')), ''), 'tcp') AS transport
    FROM assets a
    WHERE a.asset_type = 'service'
      AND jsonb_typeof(a.properties) = 'object'
      AND NOT (a.properties ? 'service_kind')
),
named AS (
    SELECT s.*, n.kind AS name_kind,
           (s.name IS NOT NULL AND s.name NOT IN ('', 'tcp', 'udp', 'sctp', 'unknown', 'general', 'tcpwrapped', 'none', '-')) AS has_name
    FROM src s LEFT JOIN kind_names n ON n.name = s.name
),
pick AS (
    SELECT d.id,
           CASE
               WHEN d.name_kind IS NOT NULL THEN d.name_kind
               WHEN d.has_name AND NOT d.guess THEN NULL
               WHEN d.sub_type = 'http' THEN 'http'
               ELSE p.kind
           END AS kind,
           CASE
               WHEN d.name_kind IS NOT NULL AND d.guess THEN 'port_guess'
               WHEN d.name_kind IS NOT NULL OR (d.sub_type = 'http' AND NOT (d.has_name AND NOT d.guess)) THEN
                   CASE WHEN d.sub_type = 'http' AND d.discovery_tool = 'httpx' THEN 'http_probe' ELSE 'reported' END
               ELSE 'port_guess'
           END AS source
    FROM named d
    LEFT JOIN kind_ports p ON p.transport = d.transport AND p.port = d.port
)
UPDATE assets a
SET properties = a.properties || jsonb_build_object(
        'service_kind', p.kind, 'service_category', c.category, 'kind_source', p.source)
FROM pick p
JOIN kind_categories c ON c.kind = p.kind
WHERE a.id = p.id AND p.kind IS NOT NULL;

-- Service kinds (docs/architecture/service-kinds.md): give every stored
-- service asset its service_kind, service_category and kind_source.
--
-- Additive and row-local: each row is classified from its own properties
-- with the registry tables of this release (printed by
-- `go run ./cmd/gen-asset-types -service-kinds-sql`), the same rules as
-- asset.ClassifyService:
--   - a protocol name of the table gives its kind: on a web service probed
--     by httpx the source is http_probe, otherwise reported (the platform
--     cannot tell after the fact which tool measured it); a name ending in
--     "?" is a guess;
--   - a protocol name outside the table gives no kind (a measured name is
--     never replaced by a guess);
--   - a web service without a name speaks http;
--   - otherwise the port's IANA default service, labelled port_guess.
-- Open ports whose protocol holds the transport (tcp, udp, sctp; written by
-- older port-scan ingest) get it moved to transport first. Rows that already
-- have a kind are left alone. updated_at is not touched (no user change).

UPDATE assets
SET properties = (properties - 'protocol')
    || CASE WHEN properties ? 'transport' THEN '{}'::jsonb
            ELSE jsonb_build_object('transport', lower(btrim(properties->>'protocol'))) END
WHERE asset_type = 'service' AND sub_type = 'open_port'
  AND jsonb_typeof(properties) = 'object'
  AND lower(btrim(properties->>'protocol')) IN ('tcp', 'udp', 'sctp');


#!/usr/bin/env bash
# =============================================================================
# backend-dir.sh: rename the Go backend directory api/ to server/ and its
# module path github.com/openctemio/openctem/api to .../server.
#
# Source layout only. Nothing a runtime sees changes: URL paths (/api/v1,
# /api/v2/sensor...), image names (openctem-api, ...), env vars, compose
# service names, the log value service=api and the historical CHANGELOG text
# are left alone.
#
# Idempotent: on a tree that is already renamed the git mv is skipped and the
# text rules find nothing, so it is safe to re-run on any branch (catch-up.sh
# uses the same rules). Run from anywhere inside the repository.
#
# Steps
#   1. git mv api server (file by file when server/ already exists).
#   2. Text rules (below) over every tracked text file.
#   3. gofmt the Go files that changed (import blocks re-sort).
#   4. server/scripts/check-proto.sh --generate (the generated protobuf code embeds the module path
#      in a length-prefixed descriptor), then make generate (the contract files
#      are generated, never committed).
#
# Env: MOVE_ONLY=1 stops after step 1 (the pure-move commit that effective-base.sh
# uses as the lint base). SKIP_GENERATE=1 skips step 4. OLD / NEW override the
# directory names. SKIP_PROTO=1 skips only the protobuf regeneration (catch-up.sh:
# the branch gets develop's generated code from the merge).
# =============================================================================
set -euo pipefail

# REPO_ROOT and RENAME_DIR are set by catch-up.sh, which runs this script from a
# copy taken out of origin/develop against a branch that does not have it yet.
ROOT="${REPO_ROOT:-$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --show-toplevel)}"
RENAME_DIR="${RENAME_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}"
cd "$ROOT"
export GOWORK=off

OLD="${OLD:-api}"
NEW="${NEW:-server}"
MODULE_BASE="github.com/openctemio/openctem"

# --- 1. move the directory --------------------------------------------------
if [ -n "$(git ls-files -- "$OLD" | head -n 1)" ]; then
  if [ ! -e "$NEW" ]; then
    echo "backend-dir: git mv $OLD $NEW"
    git mv "$OLD" "$NEW"
  else
    echo "backend-dir: $NEW/ exists, moving the remaining tracked $OLD/ files one by one"
    git ls-files -z -- "$OLD" | while IFS= read -r -d '' f; do
      dest="$NEW/${f#"$OLD"/}"
      mkdir -p "$(dirname "$dest")"
      git mv -k "$f" "$dest"
    done
  fi
fi
# git mv leaves emptied directories behind on disk (untracked leftovers such
# as bin/ or a build cache stay, with a warning).
if [ -d "$OLD" ]; then
  find "$OLD" -type d -empty -delete 2>/dev/null || true
  [ -d "$OLD" ] && echo "backend-dir: warning: untracked leftovers remain in $OLD/ (not touched)"
fi

if [ "${MOVE_ONLY:-0}" = 1 ]; then echo "backend-dir: MOVE_ONLY, stopping after the move"; exit 0; fi

# --- 2. text rules ----------------------------------------------------------
# Files NOT rewritten (history, or the tooling that has to name the old path):
#   *CHANGELOG.md                 released history
#   *.pb.go                       generated; regenerated by step 4 (see there)
#   .git-blame-ignore-revs        commit subjects
#   scripts/rename/*              this script, catch-up.sh, the guard
#   .github/scripts/check-backend-dir-name*.sh   the inventory guard and its test
#                                 (they name the old path on purpose)
#   .github/scripts/effective-base.sh   greps a historical commit subject
#   **/migrations/**/*.sql        a merged migration never changes (CI refuses
#                                 edits; the image-diff gate proves it): their
#                                 comments keep naming the old layout
EXCLUDES=(
  ':(exclude,glob)**/CHANGELOG.md'
  ':(exclude).git-blame-ignore-revs'
  ':(exclude,glob)scripts/rename/**'
  ':(exclude).github/scripts/check-backend-dir-name.sh'
  ':(exclude).github/scripts/check-backend-dir-name.test.sh'
  ':(exclude).github/scripts/effective-base.sh'
  ':(exclude,glob)**/node_modules/**'
  ':(exclude,glob)**/package-lock.json'
  ':(exclude,glob)**/*.pb.go'
  ':(exclude,glob)**/migrations/**/*.sql'
)

# Repo-root names inside the old directory. A bare "api/" followed by one of
# these is a repo path; "api/v1/...", "api/clients", "api/error" are URLs or
# web source folders and never match.
TOP='api/openapi|internal|pkg|cmd|configs|deploy|docs|ee|migrations|proto|scripts|tests|tools|changelog\.d|go\.mod|go\.sum|Makefile|Dockerfile|docker-compose|CHANGELOG|CLAUDE|README|LICENSE|trivy\.yaml|\.air\.toml|\.golangci|\.dockerignore|\.gitignore|\.gitleaksignore|\.betterleaks|\.pre-commit-config|\.gitattributes|\.env|\*|\.\.\.'

PERL_PROG="$(mktemp)"
trap 'find "$PERL_PROG" -delete' EXIT
# The rules live in a quoted heredoc (no shell interpolation); the names come
# from the environment.
cat > "$PERL_PROG" <<'PERL'
BEGIN {
  $old = $ENV{OLD}; $new = $ENV{NEW}; $mod = $ENV{MODULE_BASE}; $top = $ENV{TOP};
  $w = '[\w./~{}$\x01-]';          # characters that must not precede a repo path
                                   # (\x01 marks a protected path, see R0)
  use File::Basename qw(dirname);
  use File::Spec;
  # Does <rel>, read relative to the current file's directory, name an existing
  # path? (Files are rewritten after the move, so this is the new tree.)
  sub exists_rel { my ($rel) = @_; my $d = dirname($ARGV); return -e File::Spec->catfile($d, $rel); }
  # Does <ups>api (a run of ../ then the directory) resolve to <root>/api from
  # the current file?
  sub at_root { my ($ups) = @_; my $n = () = $ups =~ m{\.\./}g; my @p = split m{/}, dirname($ARGV); @p = () if dirname($ARGV) eq '.'; return $n == scalar(@p); }
}
# R0 protect relative links and paths that resolve next to the file itself:
#    server/docs/README.md links api/README.md, which is server/docs/api/README.md.
#    The \x01 marker keeps every later rule off them; it is removed at the end.
s{(\]\(|\]: |\(|`|["'])(\Q$old\E/[^)\s`"'#]+)}{exists_rel($2) ? "$1\x01$2" : "$1$2"}ge;
# A line marked "rename-guard: allow" names the old layout on purpose (it
# reads an old commit): leave it as it is.
next if /rename-guard: allow/;
# R1 module path. "openctem/api" never matches "openctem-api" (the image) nor
#    "openctem/api-x" (hyphen).
s{(openctemio/openctem)/\Q$old\E(?![A-Za-z0-9_-])}{$1/$new}g;
# (No rule for the swagger definition names github_com_openctemio_openctem_api_*:
#  they are part of the published OpenAPI contract and stay as they are. swag
#  derives them from the module path, so `make swagger` and the Dockerfile map
#  the new spelling back; see backend-dir.d/40-swagger-stable-names.patch.)
# R2 GitHub tree/blob links into the old directory.
s{(openctemio/openctem/(?:blob|tree)/[^/\s)`"']+)/\Q$old\E(?=[/)\s`"']|$)}{$1/$new}g;
# R3 a repo path: api/<known top-level name>. Not preceded by a word char, "-",
#    ".", "/" (a URL or the web source folder), "~", "{", "}" or "$". Known
#    names only, so api/v1/..., api/clients, api/error never match.
s{(?<!$w)\Q$old\E/(?=(?:$top))}{$new/}g;
# R3b a path right after a literal \n inside a printf/echo string.
s{(\\n)\Q$old\E/(?=(?:$top))}{$1$new/}g;
# R4 relative or variable-rooted repo paths: ./api/x ../api/x $ROOT/api/x
#    ${ROOT}/api/x $(REPO)/api/x, same known names.
s{((?:\.\.?|\$\{?[A-Za-z0-9_]+\}?|\$\([A-Za-z_]+\))/)\Q$old\E/(?=(?:$top))}{$1$new/}g;
#    ... and the directory itself after a variable root only: "$ROOT/api", $d/api)
#    (never ./api or ../api: in web sources those are relative imports).
s{(\$\{?[A-Za-z0-9_]+\}?/|\$\([A-Za-z_]+\)/)\Q$old\E(?=["'`)\s;]|$)}{$1$new}g;
# R5 the directory by itself: "api/", `api/`, (api/), "api/ ", end of line.
#    Not under web/: its docs draw their own src/app/api/ folder as "api/".
s{(?<!$w)\Q$old\E/(?=[\s`"'),;:]|\.(?:\s|$)|$)}{$new/}g unless $ARGV =~ m{^web/};
#    The generated web registry header (web/ is exempt from R5 above).
s{\b(in|from the) \Q$old\E/(?= to regenerate| after changing| directory)}{$1 $new/}g;
#    ../api/ standing alone in a doc or script (never in TS/JS: relative imports).
s{(?<![\w.-])(\.\./)\Q$old\E/(?=[\s`"'),;:]|$)}{$1$new/}g unless $ARGV =~ m{\.(?:[cm]?[jt]sx?|json)$};
# R6 commands and keys that take the directory as an argument:
#    -C api, cd api, pushd api (also ./api)
s{(?<![\w./-])(-C|cd|pushd)(\s+)(?:\./)?\Q$old\E(?![\w/-])}{$1$2$new}g;
#    working-directory: api, context: ./api, path: api, ...
s{\b(working-directory|context|workdir|cache-dependency-path|path|root|dir):(\s*)(\./)?\Q$old\E(?=\s|$|/|["'])}{$1:$2$3$new}g;
#    tree api (image-key.sh), [[ -d api ]], "... api || true"
s{(?<![\w-])(tree\s+|-[dfe]\s+)\Q$old\E(?![\w/-])}{$1$new}g;
s{(?<=["']\s)\Q$old\E(?=\s*\|\|\s*true)}{$new}g;
#    dependabot: directory: "/api"  directories: ["/api", "/web"]
s{(\bdirectory:\s*["']?)/\Q$old\E(?![\w-])}{$1/$new}g;
s{(\bdirectories:\s*\[[^\]]*?["'])/\Q$old\E(?![\w-])}{$1/$new}g if $ARGV =~ m{(^|/)dependabot\.yml$};
# R7 owner-file and path-list syntax with a leading slash: /api/ /api/deploy
if ($ARGV =~ m{(^|/)(CODEOWNERS|dependabot\.yml|security-paths\.yml|labeler\.yml|check-edition-fence\.sh|\.gitignore|\.dockerignore|\.gitattributes)$}) {
  s{(?<![\w.-])/\Q$old\E/(?=(?:$top)\b|\*|\s|$)}{/$new/}g;
}
# R6b the directory as a bare word argument:
#    Trivy scan-ref: 'api'; TREE_PATHS: web api Makefile ...;
#    docker build ... --target production api (the build context, last word);
#    ${MIGRATIONS_DIR:-api/migrations} (a shell default).
s{\b(scan-ref:\s*["']?)\Q$old\E(?=["']?\s*$)}{$1$new}g;
s{(?<=[\s:])\Q$old\E(?=\s|$)}{$new}g if /TREE_PATHS[:=]/;
s{(docker (?:buildx )?build\b.*\s)\Q$old\E(\s*\\?)$}{$1$new$2};
s{(:-)\Q$old\E/(?=(?:$top))}{$1$new/}g;
# R9 anchored regexes (^api/ -> ^server/) and the security gate test fixtures, and a bare "api" scan target on its own line (api-security.yml).
s{\^\Q$old\E/}{^$new/}g;   # any anchored regex or grep: .githooks/pre-commit, precheck.sh, security_gate.py
s{(["'])\Q$old\E/(?=[a-z_]+\.go\b)}{$1$new/}g if $ARGV =~ m{(^|/)security_gate_test\.py$};
s{^(\s+)\Q$old\E$}{$1$new} if $ARGV =~ m{(^|/)api-security\.yml$};
# R8b test fixtures naming the area paths: TREE_PATHS="api Makefile", areaid "$A" api Makefile
if ($ARGV =~ m{\.test\.sh$}) {
  s{(?<=["\s])\Q$old\E(?= Makefile)}{$new}g;
}
# R8 test fixtures that build a throwaway repository with an api/ directory
#    (.test.sh files and the release tests): api/<anything> and <dir>/api/<x>,
#    but never a URL (/api/v1, /api/health).
if ($ARGV =~ m{(\.test\.sh|/tests/test_[^/]*\.sh)$}) {
  s{(?<![\w.\$-])\Q$old\E/(?=[A-Za-z_])(?!(?:v\d|health))}{$new/}g;
  s{(?<![\w.:-])((?:\$\{?[A-Za-z0-9_]+\}?/)(?:[a-z]+/)?)\Q$old\E/(?=[A-Za-z_])(?!(?:v\d|health))}{$1$new/}g;
}
# R10 Python path building: ROOT / "api" (pathlib) and
#    os.path.join(x, "api", "changelog.d") with a known name next.
if ($ARGV =~ m{\.py$}) {
  s{(/\s*)(["'])\Q$old\E\2}{$1$2$new$2}g;
  s{(os\.path\.join\([^)]*?,\s*)(["'])\Q$old\E\2(?=\s*,\s*["'](?:$top))}{$1$2$new$2}g;
}
# R11 a workflow expression as the root: ${{ github.workspace }}/api/configs
s{(\$\{\{\s*[\w.]+\s*\}\}/)\Q$old\E/(?=(?:$top))}{$1$new/}g;
# R12 ../../api (a run of ../ that resolves to the repository root, then the
#    directory), in any file: the web tests read the Go sources this way.
s{(?<![\w.])((?:\.\./)+)\Q$old\E(?=[/"'`\s)]|$)}{at_root($1) ? "$1$new" : "$1$old"}ge;
# R13 a docker bake build context: context = "api"
s{(\bcontext\s*=\s*")\Q$old\E(")}{$1$new$2}g if $ARGV =~ m{\.hcl$};
# R14 the directory as the path argument of a listing command: find api -name ...
s{(\b(?:find|ls|du|gofmt -l|git ls-files)\s+)\Q$old\E(?=\s|$)}{$1$new}g;
# R15 security-lint.sh's workspace sibling list: for sibling in api agent sdk-go
#    (never the image-key lists "api web console allinone").
s{(\bin\s+)\Q$old\E(?=\s+agent\s+sdk-go\b)}{$1$new}g;
s{(<root>/\{)\Q$old\E(?=,agent,sdk-go\})}{$1$new}g;
# R0 end: drop the protection marker.
s{\x01}{}g;
PERL

echo "backend-dir: rewriting repo paths and the module path"
export OLD NEW MODULE_BASE TOP
# git grep -l lists the text files that mention the old name at all (-I skips
# binaries); only those go through perl.
{ git grep -Ilz -e "$OLD" -- . "${EXCLUDES[@]}" || true; } \
  | xargs -0 -r perl -i -p "$PERL_PROG"

# --- 2b. hand-written edits ---------------------------------------------------
# Logic that cannot be a text rule lives as patches in backend-dir.d/, applied on
# top of the rule output: upgrade-test.sh reads the PREVIOUS release (still laid
# out as api/) and effective-base.sh needs the rename commit as the lint base.
# A patch that is already applied (reverse-applies cleanly) is skipped.
for p in "$RENAME_DIR"/backend-dir.d/*.patch; do
  [ -f "$p" ] || continue
  if git apply --check "$p" 2>/dev/null; then
    git apply "$p"; echo "backend-dir: applied $(basename "$p")"
  elif git apply -R --check "$p" 2>/dev/null; then
    echo "backend-dir: $(basename "$p") already applied"
  else
    echo "backend-dir: ERROR $(basename "$p") neither applies nor is applied; refresh it by hand" >&2; exit 1
  fi
done

# --- 2c. prettier on the web files the rules changed --------------------------
# "server" is longer than "api", so some lines now wrap. The pre-commit hook
# formats staged web files; doing it here makes the result the same whether or
# not the commit goes through the hook (catch-up.sh depends on that: develop's
# copy and the branch's copy must be byte-identical or they conflict).
webfiles="$(git diff --name-only -z -- 'web/*.ts' 'web/*.tsx' 'web/*.json' 'web/*.md' 'web/*.yml' 'web/*.yaml' | tr '\0' '\n' | sed 's|^web/||')"
if [ -n "$webfiles" ]; then
  if [ -x web/node_modules/.bin/prettier ]; then
    echo "backend-dir: prettier on $(printf '%s\n' "$webfiles" | wc -l) web files"
    # shellcheck disable=SC2086
    (cd web && printf '%s\n' "$webfiles" | xargs -r node_modules/.bin/prettier --write --log-level warn)
  else
    echo "backend-dir: WARNING web/node_modules is missing: the web files were not formatted (npm ci in web/, then run again)" >&2
  fi
fi

# --- 3. gofmt ---------------------------------------------------------------
echo "backend-dir: gofmt"
# Only the Go files the rules just changed (worktree against index; step 1 is
# already staged): other files may not be gofmt-clean on purpose (generated).
# Generated files ("Code generated ... DO NOT EDIT") are left as the generator
# wrote them: some generators do not emit gofmt-clean output, and the drift
# tests compare the committed file with the generator's output byte for byte.
git diff --name-only -z -- '*.go' | while IFS= read -r -d '' f; do
  head -n 20 "$f" | grep -q 'Code generated .* DO NOT EDIT' || printf '%s\0' "$f"
done | xargs -0 -r gofmt -w

# --- 4. generate ------------------------------------------------------------
if [ "${SKIP_GENERATE:-0}" != 1 ]; then
  # The generated sensor protocol code embeds the Go package path in a
  # length-prefixed descriptor: a text rewrite corrupts it (the binary panics at
  # start), so it is regenerated from the .proto instead (buf, pinned tools).
  if [ "${SKIP_PROTO:-0}" != 1 ]; then
    echo "backend-dir: $NEW/scripts/check-proto.sh --generate"
    bash "$NEW/scripts/check-proto.sh" --generate
  fi
  echo "backend-dir: make generate"
  make generate-api
  if [ -d web/node_modules ]; then make generate-web; else echo "backend-dir: web/node_modules missing, skipped generate-web"; fi
fi
echo "backend-dir: done."
